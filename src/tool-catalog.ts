export function expandSecurityTerms(tokens: Iterable<string>): Set<string> {
  const expanded = new Set<string>();
  for (const token of tokens) {
    for (const group of SECURITY_SYNONYM_GROUPS) {
      if (group.includes(token)) {
        for (const alias of group) expanded.add(alias);
      }
    }
  }
  return expanded;
}

export function toolNote(name: string): string | undefined {
  const key = String(name).toLowerCase();
  return Object.hasOwn(TOOL_NOTES, key) ? TOOL_NOTES[key] : undefined;
}
