const BY_ID = new Map(TECHNIQUES.map((card) => [card.id, card]));

export function techniqueCard(id: string): TechniqueCard {
  const card = BY_ID.get(String(id).trim());
  if (!card) throw new Error("Unknown technique card");
  return card;
}

export function techniqueCards(phase?: TechniquePhase): TechniqueCard[] {
  if (phase === undefined) return [...TECHNIQUES];
  if (!TECHNIQUE_PHASES.includes(phase))
    throw new Error("Unknown technique phase");
  return TECHNIQUES.filter((card) => card.phase === phase);
}

/** Everything that is not `carded`: the gaps a session must name, never fill by guessing. */
export function techniqueGaps(): TechniqueCard[] {
  return TECHNIQUES.filter((card) => card.status !== "carded");
}

/** A compact table for injection: one line per card, bounded by construction. */
export function techniqueTable(): string {
  return TECHNIQUES.map(
    (card) =>
      `${card.id} ${card.status} ${card.owner ?? "-"} ${card.name}`,
  ).join("\n");
}
