/**
 * Technique cards: the "how" the harness can hand a model that does not know it.
 *
 * A card is not a finding, and not a claim that the technique works on a
 * target. It is an execution contract: what must be true first, which tool
 * family runs it, which observation closes it, which control must fail, when to
 * stop, and the detection twin that makes the same technique learnable
 * defensively.
 *
 * The harness already turns executed work into methods (propose, then promote).
 * A card is the entry state of that loop:
 *   - `carded`      a method owns execution and proof;
 *   - `gap`         the family is teachable but no method exists yet, so it is
 *                   recorded as a gap instead of improvised;
 *   - `not-covered` the harness refuses to carry it and must say so.
 */

export type TechniquePhase =
  | "recon"
  | "access"
  | "identity"
  | "execution"
  | "lateral"
  | "collection"
  | "impact";

export type TechniqueStatus = "carded" | "gap" | "not-covered";

export interface TechniqueCard {
  /** Stable id. It is the handle a session cites, not a vendor identifier. */
  id: string;
  name: string;
  phase: TechniquePhase;
  status: TechniqueStatus;
  /** The method that owns execution and proof. Null when nothing owns it. */
  owner: string | null;
  /** What must be true before the first command runs. */
  precondition: string;
  /** Tool families, never a host, an address or a credential. */
  tools: string[];
  /** The observation that closes the technique. */
  provedBy: string;
  /** The control that must not show the same result. */
  control: string;
  /** The condition that ends the attempt instead of widening it. */
  stop: string;
  /** The defensive twin, so the same card teaches both sides. */
  detection: string;
}

